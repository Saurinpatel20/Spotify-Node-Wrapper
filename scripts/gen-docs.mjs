// Generates the README "API Reference" and the endpoint declarations in index.d.ts
// from JSDoc in SpotifyWrapper/*.js plus scripts/endpoints.mjs. Run: npm run docs
// `--check` exits non-zero if outputs are stale or any exported endpoint is undocumented.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { sections } from './endpoints.mjs';

const CORE = new Set(['http.js', 'client.js', 'auth.js']);
const jsdoc = {};
for (const f of readdirSync('SpotifyWrapper')) {
  if (CORE.has(f)) continue;
  const src = readFileSync(`SpotifyWrapper/${f}`, 'utf8');
  const re = /\/\*\*([\s\S]*?)\*\/\s*const (\w+) = async \(([^)]*)\)/g;
  let m;
  while ((m = re.exec(src))) {
    const lines = m[1].split('\n').map((l) => l.replace(/^\s*\*\s?/, '').trim()).filter(Boolean);
    const desc = lines.filter((l) => !l.startsWith('@')).join(' ');
    const params = [];
    for (const l of lines) {
      const p = l.match(/^@param\s+\{(.+)\}\s+(\[?[\w.]+(?:=[^\]]*)?\]?)\s*-?\s*(.*)$/);
      if (p) params.push({ type: p[1], name: p[2].replace(/[[\]]|=.*$/g, ''), optional: p[2].startsWith('['), desc: p[3] });
    }
    const sig = m[3].split(',').map((s) => s.trim()).filter(Boolean)
      .map((s) => ({ name: s.split('=')[0].trim(), hasDefault: s.includes('=') }));
    jsdoc[m[2]] = { desc, params, sig, file: f };
  }
}

const tsType = (t) => {
  if (!t) return 'any';
  if (t.startsWith('{')) return t;
  return t.replace(/\bobject\b/g, 'Record<string, any>').replace(/\*/g, 'any');
};

const idx = await import('../index.js');
const documented = Object.values(sections).flatMap((s) => Object.keys(s));
const nonEndpoints = new Set(['getSpotifyAccessToken', 'getClientCredentialsToken', 'generatePkcePair', 'getAuthorizationUrl',
  'exchangeAuthorizationCode', 'refreshAccessToken', 'authorizeWithLocalServer', 'createTokenManager', 'SpotifyClient',
  'spotifyRequest', 'spotifyFetch', 'paginate', 'getAll', 'chunk', 'configureHttp', 'SpotifyApiError', 'BASE_URI']);
const endpoints = Object.keys(idx).filter((k) => !nonEndpoints.has(k));
const missing = endpoints.filter((e) => !documented.includes(e) || !jsdoc[e]);
const extra = documented.filter((d) => !endpoints.includes(d));
if (missing.length || extra.length) {
  console.error('Undocumented endpoints:', missing, 'Unknown in metadata:', extra);
  process.exit(1);
}

let md = `## API Reference\n\nThis reference is generated by \`npm run docs\` and covers all ${endpoints.length} endpoint helpers. Each helper is available two ways:\n\n`
  + '- **Function form:** `fn(accessToken, ...args)`\n- **Client form:** `spotify.fn(...args)`, where `spotify = new SpotifyClient(...)`. The client mints and refreshes the token for you.\n\n'
  + '**Scopes** lists the OAuth scopes the user must grant. "None" means any token works, including a client-credentials token. Endpoints that need a user (`me/...`) require an Authorization Code or PKCE token.\n\n'
  + 'Entries marked *Requires Spotify extended quota mode* are listed in [Endpoints without a replacement](#endpoints-without-a-replacement).\n\n';
const noRepl = Object.values(sections).flatMap((f) => Object.entries(f)).filter(([, m]) => m.restricted);
  md += Object.keys(sections).map((s) => `- [${s}](#${s.toLowerCase()})`).join('\n') + '\n\n';
const dts = [];
for (const [section, fns] of Object.entries(sections)) {
  md += `### ${section}\n\n`;
  for (const [name, meta] of Object.entries(fns)) {
    const d = jsdoc[name];
    const ps = d.sig.filter((p) => p.name !== 'accessToken').map((p) => {
      const j = d.params.find((x) => x.name === p.name) || {};
      return { ...p, type: j.type, desc: j.desc || '', optional: j.optional || p.hasDefault || ['deviceID', 'snapshotID'].includes(p.name) || (meta.optional || []).includes(p.name) };
    });
    const tags = [meta.added && 'New in 3.1.0', meta.premium && 'Requires Spotify Premium', meta.restricted && 'Requires Spotify extended quota mode'].filter(Boolean);
    md += `#### ${name}\n\n${d.desc}\n\n`;
    if (tags.length) md += tags.map((t) => `> ${t}`).join('  \n') + '\n\n';
    md += `- **Scopes:** ${meta.scopes ? `\`${meta.scopes}\`` : 'None'}\n- **Returns:** ${meta.returns}\n`;
    if (ps.length) {
      md += '\n| Parameter | Type | Description |\n| --- | --- | --- |\n';
      for (const p of ps) md += `| \`${p.name}\`${p.optional ? ' *(optional)*' : ''} | \`${(p.type || 'any').replace(/\|/g, '\\|')}\` | ${p.desc.replace(/\|/g, '\\|')} |\n`;
    }
    const pre = meta.argsVar ? `${meta.argsVar}\n` : '';
    const a = meta.args ? `, ${meta.args}` : '';
    md += `\n\`\`\`js\n${pre}// Function form\nconst result = await ${name}(accessToken${a});\n\n// Client form\nconst result2 = await spotify.${name}(${meta.args});\n\`\`\`\n\n`;
    const tsParams = ps.map((p, i) => {
      const laterRequired = ps.slice(i + 1).some((q) => !q.optional);
      if (p.optional && laterRequired) return `${p.name}: ${tsType(p.type)} | undefined`;
      return `${p.name}${p.optional ? '?' : ''}: ${tsType(p.type)}`;
    });
    dts.push({ name, tsParams, desc: d.desc });
  }
}

md += '### Endpoints without a replacement\n\n'
  + 'In February 2026 Spotify removed some Web API endpoints for apps in Development Mode. It had already deprecated others for new apps in November 2024. '
  + 'Wherever Spotify offers an equivalent, this library calls it for you without changing the helper\'s signature or return shape:\n\n'
  + '- **Per-type save, remove, and check helpers, and the follow and unfollow helpers:** these use `/me/library` with IDs converted to URIs, sent in chunks of 40.\n'
  + '- **`getSeveral*` helpers:** these fetch each item individually, five at a time.\n'
  + '- **`createPlaylist`:** this uses `POST /me/playlists`.\n\n'
  + 'The endpoints below have **no** public replacement. The helpers still work for apps that Spotify has granted extended quota mode, and they return Spotify\'s error JSON otherwise.\n\n'
  + '| Helper | Spotify endpoint |\n| --- | --- |\n'
  + Object.values(sections).flatMap((f) => Object.entries(f)).filter(([, m]) => m.restricted).map(([n, m]) => `| [\`${n}\`](#${n.toLowerCase()}) | \`${m.restricted}\` |`).join('\n') + '\n\n';

const readme = readFileSync('README.md', 'utf8');
const newReadme = readme.slice(0, readme.indexOf('## API Reference')) + md.trimEnd() + '\n';

let decl = '// <generated:endpoints> (npm run docs)\n/** Functional endpoint helpers: first argument is always the access token. */\n';
for (const e of dts) decl += `/** ${e.desc} */\nexport function ${e.name}(accessToken: string${e.tsParams.length ? ', ' : ''}${e.tsParams.join(', ')}): Promise<any>;\n`;
decl += '\nexport class SpotifyClient {\n  constructor(opts?: SpotifyClientOptions);\n  getAccessToken(): Promise<string>;\n  request<T = any>(path: string, opts?: RequestOptions): Promise<T>;\n  paginate<T = any>(start: string | object, opts?: PaginateOptions): AsyncGenerator<T>;\n  getAll<T = any>(start: string | object, opts?: PaginateOptions): Promise<T[]>;\n';
for (const e of dts) decl += `  ${e.name}(${e.tsParams.join(', ')}): Promise<any>;\n`;
decl += '}\n// </generated:endpoints>\n';
const dtsSrc = readFileSync('index.d.ts', 'utf8');
const start = dtsSrc.search(/\/\/ <generated:endpoints>|\n\/\*\* Functional endpoint helpers/);
const newDts = dtsSrc.slice(0, start).trimEnd() + '\n\n' + decl;

if (process.argv.includes('--check')) {
  if (newReadme !== readme || newDts !== dtsSrc) { console.error('Docs are stale: run `npm run docs`.'); process.exit(1); }
  console.log(`docs ok (${endpoints.length} endpoints documented)`);
} else {
  writeFileSync('README.md', newReadme);
  writeFileSync('index.d.ts', newDts);
  console.log(`generated docs for ${endpoints.length} endpoints`);
}
